/* AES round constants for key expansion (FIPS 197 §5.2). Only the low
 * byte is non-zero; placed in the high byte of a 32-bit word to XOR
 * directly into the leading word of each Rcon-using key column. */
static const uint8_t RCON[11] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

static uint32_t T0[256];
static uint32_t T1[256];
static uint32_t T2[256];
static uint32_t T3[256];
static uint32_t T4[256];

/* GF(2^8) doubling under reduction polynomial x^8 + x^4 + x^3 + x + 1
 * (0x11b). Equivalent to multiplication by {02} in MixColumns. */
static uint8_t xtime(uint8_t b) {
    return (uint8_t)((b << 1) ^ (((b >> 7) & 1u) * 0x1bu));
}

static void init_tables(void) {
    for (int a = 0; a < 256; a++) {
        uint8_t s = SBOX[a];
        uint8_t s2 = xtime(s);          /* {02}·s */
        uint8_t s3 = (uint8_t)(s2 ^ s); /* {03}·s = {02}·s ^ s */

        /* Column produced by SubBytes+MixColumns when the input byte is
         * at row 0 of a column: ({02}·s, s, s, {03}·s). We pack
         * big-endian-ish into 32 bits as (s2 << 24) | (s << 16) | (s << 8) | s3
         * which matches the Python tables fallback word convention. */
        uint32_t t0 = ((uint32_t)s2 << 24) |
                      ((uint32_t)s  << 16) |
                      ((uint32_t)s  <<  8) |
                      ((uint32_t)s3);
        T0[a] = t0;
        /* T1 = T0 rotated right by 8 bits, T2 by 16, T3 by 24. */
        T1[a] = (t0 >> 8)  | (t0 << 24);
        T2[a] = (t0 >> 16) | (t0 << 16);
        T3[a] = (t0 >> 24) | (t0 << 8);
        /* T4: SubBytes only, no MixColumns. Used in the final round. */
        T4[a] = ((uint32_t)s << 24) |
                ((uint32_t)s << 16) |
                ((uint32_t)s <<  8) |
                ((uint32_t)s);
    }
}

/* AES-128 key expansion. Produces 44 words (11 round keys * 4 words). */
static void key_expansion(const uint8_t key[16], uint32_t rk[44]) {
    for (int i = 0; i < 4; i++) {
        rk[i] = ((uint32_t)key[4*i]   << 24) |
                ((uint32_t)key[4*i+1] << 16) |
                ((uint32_t)key[4*i+2] <<  8) |
                ((uint32_t)key[4*i+3]);
    }
    for (int i = 4; i < 44; i++) {
        uint32_t temp = rk[i - 1];
        if ((i % 4) == 0) {
            /* RotWord: rotate left by 8 bits. */
            uint32_t rot = (temp << 8) | (temp >> 24);
            /* SubWord: S-box every byte. */
            uint8_t b0 = SBOX[(rot >> 24) & 0xff];
            uint8_t b1 = SBOX[(rot >> 16) & 0xff];
            uint8_t b2 = SBOX[(rot >>  8) & 0xff];
            uint8_t b3 = SBOX[ rot        & 0xff];
            uint32_t sub = ((uint32_t)b0 << 24) |
                           ((uint32_t)b1 << 16) |
                           ((uint32_t)b2 <<  8) |
                           ((uint32_t)b3);
            temp = sub ^ ((uint32_t)RCON[i / 4] << 24);
        }
        rk[i] = rk[i - 4] ^ temp;
    }
}

static void aes128_encrypt_block(const uint32_t rk[44],
                                 const uint8_t in[16],
                                 uint8_t out[16]) {
    uint32_t s0, s1, s2, s3;
    uint32_t t0, t1, t2, t3;

    /* Load plaintext as 4 big-endian 32-bit words and add round key 0. */
    s0 = (((uint32_t)in[ 0]) << 24) | (((uint32_t)in[ 1]) << 16) |
         (((uint32_t)in[ 2]) <<  8) |  ((uint32_t)in[ 3]);
    s1 = (((uint32_t)in[ 4]) << 24) | (((uint32_t)in[ 5]) << 16) |
         (((uint32_t)in[ 6]) <<  8) |  ((uint32_t)in[ 7]);
    s2 = (((uint32_t)in[ 8]) << 24) | (((uint32_t)in[ 9]) << 16) |
         (((uint32_t)in[10]) <<  8) |  ((uint32_t)in[11]);
    s3 = (((uint32_t)in[12]) << 24) | (((uint32_t)in[13]) << 16) |
         (((uint32_t)in[14]) <<  8) |  ((uint32_t)in[15]);
    s0 ^= rk[0]; s1 ^= rk[1]; s2 ^= rk[2]; s3 ^= rk[3];

    /* Rounds 1..9: T-table merged SubBytes+ShiftRows+MixColumns+AddRoundKey. */
    for (int r = 1; r < 10; r++) {
        t0 = T0[(s0 >> 24) & 0xff] ^ T1[(s1 >> 16) & 0xff] ^
             T2[(s2 >>  8) & 0xff] ^ T3[ s3        & 0xff] ^ rk[r*4 + 0];
        t1 = T0[(s1 >> 24) & 0xff] ^ T1[(s2 >> 16) & 0xff] ^
             T2[(s3 >>  8) & 0xff] ^ T3[ s0        & 0xff] ^ rk[r*4 + 1];
        t2 = T0[(s2 >> 24) & 0xff] ^ T1[(s3 >> 16) & 0xff] ^
             T2[(s0 >>  8) & 0xff] ^ T3[ s1        & 0xff] ^ rk[r*4 + 2];
        t3 = T0[(s3 >> 24) & 0xff] ^ T1[(s0 >> 16) & 0xff] ^
             T2[(s1 >>  8) & 0xff] ^ T3[ s2        & 0xff] ^ rk[r*4 + 3];
        s0 = t0; s1 = t1; s2 = t2; s3 = t3;
    }

    /* Round 10: SubBytes + ShiftRows + AddRoundKey, no MixColumns. T4 has
     * the same byte in all four lanes; we mask to keep only the lane we
     * need so the XOR composes a properly shifted-row column. */
    t0 = (T4[(s0 >> 24) & 0xff] & 0xff000000u) ^
         (T4[(s1 >> 16) & 0xff] & 0x00ff0000u) ^
         (T4[(s2 >>  8) & 0xff] & 0x0000ff00u) ^
         (T4[ s3        & 0xff] & 0x000000ffu) ^ rk[40];
    t1 = (T4[(s1 >> 24) & 0xff] & 0xff000000u) ^
         (T4[(s2 >> 16) & 0xff] & 0x00ff0000u) ^
         (T4[(s3 >>  8) & 0xff] & 0x0000ff00u) ^
         (T4[ s0        & 0xff] & 0x000000ffu) ^ rk[41];
    t2 = (T4[(s2 >> 24) & 0xff] & 0xff000000u) ^
         (T4[(s3 >> 16) & 0xff] & 0x00ff0000u) ^
         (T4[(s0 >>  8) & 0xff] & 0x0000ff00u) ^
         (T4[ s1        & 0xff] & 0x000000ffu) ^ rk[42];
    t3 = (T4[(s3 >> 24) & 0xff] & 0xff000000u) ^
         (T4[(s0 >> 16) & 0xff] & 0x00ff0000u) ^
         (T4[(s1 >>  8) & 0xff] & 0x0000ff00u) ^
         (T4[ s2        & 0xff] & 0x000000ffu) ^ rk[43];

    out[ 0] = (uint8_t)(t0 >> 24); out[ 1] = (uint8_t)(t0 >> 16);
    out[ 2] = (uint8_t)(t0 >>  8); out[ 3] = (uint8_t)(t0);
    out[ 4] = (uint8_t)(t1 >> 24); out[ 5] = (uint8_t)(t1 >> 16);
    out[ 6] = (uint8_t)(t1 >>  8); out[ 7] = (uint8_t)(t1);
    out[ 8] = (uint8_t)(t2 >> 24); out[ 9] = (uint8_t)(t2 >> 16);
    out[10] = (uint8_t)(t2 >>  8); out[11] = (uint8_t)(t2);
    out[12] = (uint8_t)(t3 >> 24); out[13] = (uint8_t)(t3 >> 16);
    out[14] = (uint8_t)(t3 >>  8); out[15] = (uint8_t)(t3);
}

/* Public ABI. CTR mode with 12-byte nonce + 4-byte big-endian counter
 * starting at 0, incrementing by 1 per 16-byte block. The last block may
 * be partial; only the remaining bytes are XOR'd. */
void aes128_ctr_xor(const uint8_t key[16],
                    const uint8_t nonce[12],
                    const uint8_t *in,
                    uint8_t *out,
                    size_t len) {
    static int initialized = 0;
    if (!initialized) {
        init_tables();
        initialized = 1;
    }

    uint32_t rk[44];
    key_expansion(key, rk);

    uint8_t counter_block[16];
    uint8_t keystream[16];
    memcpy(counter_block, nonce, 12);

    uint32_t counter = 0;
    size_t off = 0;
    while (off < len) {
        counter_block[12] = (uint8_t)(counter >> 24);
        counter_block[13] = (uint8_t)(counter >> 16);
        counter_block[14] = (uint8_t)(counter >>  8);
        counter_block[15] = (uint8_t)(counter);

        aes128_encrypt_block(rk, counter_block, keystream);

        size_t remaining = len - off;
        size_t chunk = remaining < 16 ? remaining : 16;
        for (size_t i = 0; i < chunk; i++) {
            out[off + i] = in[off + i] ^ keystream[i];
        }
        off += chunk;
        counter++;
    }
}
