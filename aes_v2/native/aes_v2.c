/*
 * aes_v2.c - AES-128-CTR engine, T-table optimized (V2).
 *
 * Written from scratch for the ACV project. No third-party headers, no
 * crypto libraries, no AES-NI intrinsics. Only stdint.h / string.h /
 * stddef.h.
 *
 * Algorithm: standard 4x T-table approach (Daemen & Rijmen). The T-tables
 * T0..T3 fold SubBytes, ShiftRows, and MixColumns into a single 32-bit
 * lookup per input byte; T4 is the SubBytes-only table used in the final
 * round (which has no MixColumns). All five tables are computed at first
 * use of aes128_ctr_xor() from the FIPS 197 S-box and the MixColumns
 * matrix, using the standard GF(2^8) reduction polynomial 0x11b. Nothing
 * is imported.
 */

